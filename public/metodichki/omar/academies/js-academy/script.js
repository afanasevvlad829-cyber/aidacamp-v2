function runJS(code, outEl){
  const logs = [];
  const fakeConsole = {
    log:(...a)=>logs.push(a.map(x=>typeof x==="object"?JSON.stringify(x):String(x)).join(" ")),
    error:(...a)=>logs.push("❌ "+a.join(" ")),
    warn:(...a)=>logs.push("⚠️ "+a.join(" "))
  };
  try {
    const fn = new Function("console", `"use strict";\n${code}`);
    const ret = fn(fakeConsole);
    if (ret !== undefined) logs.push("→ " + (typeof ret==="object"?JSON.stringify(ret):String(ret)));
    outEl.textContent = logs.join("\n") || "(нет вывода)";
  } catch(e){
    outEl.textContent = "❌ Ошибка: " + e.message;
  }
}

