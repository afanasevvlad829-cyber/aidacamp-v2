#!/usr/bin/env bash
# Ежедневный прогон SEO-конвейера seo-wave-cycle от имени claude-run.
#
# CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS=0 — критично. Без неё harness убивает
# фоновые задачи через 600 с («Background tasks still running after 600s;
# terminating») и обрывает прогон на середине: 22.08.2026 цикл так остановился,
# сделав 13 волн из 135 запланированных страниц, при этом три редактора ещё
# дописывали правки. Ноль = ждать сколько нужно.
#
# Промпт вынесен в скрипт, потому что в crontab строка такой длины не влезает
# («command too long» при попытке 22.08.2026).
set -uo pipefail
cd "$HOME/aidacamp-v2" || exit 1
git fetch -q origin dev || true

export CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS=0

# PID-файл для сторожа (/opt/scripts/seo-wave-watchdog.sh). До 26.08.2026 сторож
# определял занятость через pgrep по строке «claude -p» и трижды за день ошибся:
# ловил посторонние процессы и диагностические команды оператора, после чего
# молча не поднимал прогон. Файл убирается при любом выходе, включая прерывание.
PIDFILE=/tmp/seo-wave-run.pid
echo $$ > "$PIDFILE"
trap 'rm -f "$PIDFILE"' EXIT INT TERM

claude -p "Запусти цикл по скиллу seo-wave-cycle (см. ~/.claude/skills/seo-wave-cycle/SKILL.md). Пройди все 4 сайта — aidacamp, codims, icepartners, vlad-a, беря цели из бэклога seo_keyword_backlog со статусом new. Соблюдай градацию вмешательства по глубине из шапки скилла: 11-15 лёгкое вплетение лемм, 16-25 переработка секций, 26-50 полноценный рерайт по ТЗ с выдачи, глубже 50 сперва диагностика индексации, а не текст. Обязательны: перелинковка в каждой волне и ревью старшей моделью перед мержем — мержить только при вердикте APPROVE, при BLOCK оставить PR на ручной разбор. Каждое добавленное предложение обязано быть полезно читателю само по себе; предложение ради леммы = BLOCK. Создание новых страниц (фронт D) — только через decision_log и Telegram-бот, не мержить самостоятельно. Автономно до результата, без уточняющих вопросов."
