/**
 * html-minify-cached.mjs — Astro-интеграция: минификация HTML с кэшем по содержимому.
 *
 * Зачем. @playform/compress минифицирует ВСЕ 344 страницы на каждой сборке — 74с
 * (замер по логу CI 14.08.2026, run 31770755865: сам astro build ~30с, compress 74с
 * сверху). При этом типичная правка задевает 1-5 страниц: остальные 339 прогоняются
 * через html-minifier-terser ради байт-в-байт того же результата.
 *
 * Как. Ключ кэша — sha1 СОДЕРЖИМОГО файла, не его путь и не коммит. Поэтому кэш
 * остаётся полезным даже когда устарел: совпадут все страницы, которых правка не
 * коснулась. Промах — минифицируем и кладём в кэш.
 *
 * Почему не in-memory и не по mtime: сборка каждый раз пишет dist/ заново, mtime у
 * всех файлов свежий. Содержимое — единственный честный признак «эта страница не
 * изменилась».
 *
 * Заменяет ТОЛЬКО HTML-часть @playform/compress (в astro.config.mjs у того стоит
 * HTML: false). CSS/JS остаются за ним: их там 32 и 110 файлов, экономия 5.28 КБ и
 * 7.7 КБ — овчинка не стоит отдельного кэша.
 *
 * ⚠️ Опции ниже — копия дефолтов @playform/compress (его
 * Target/Variable/HTML/html-minifier-terser.js) и должны с ними совпадать: при
 * расхождении сборка начнёт давать другой HTML, чем раньше. Импортировать их из
 * внутренностей пакета намеренно не стал — это непубличный путь, отвалится на
 * первом же обновлении.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { minify } from 'html-minifier-terser';

// Копия дефолтов @playform/compress. processScripts важен для JSON-LD-схем
// (application/ld+json) — они есть на каждой странице (FAQ/BreadcrumbList).
const MINIFY_OPTIONS = {
  caseSensitive: true,
  collapseInlineTagWhitespace: false,
  collapseWhitespace: true,
  continueOnParseError: true,
  html5: true,
  ignoreCustomComments: [/^\s*#/, /.*\$.*/, /^\s*\[/, /^\s*\]/, /^\s*!/, /^\s*\//, /^\s*astro:.*/, /^\s*astro:end/],
  includeAutoGeneratedTags: true,
  keepClosingSlash: true,
  minifyCSS: true,
  minifyJS: true,
  minifyURLs: false,
  noNewlinesBeforeTagClose: true,
  preventAttributesEscaping: false,
  processConditionalComments: false,
  processScripts: [
    'application/ecmascript', 'application/javascript', 'application/json',
    'application/ld+json', 'application/manifest+json', 'application/schema+json',
    'application/xhtml+xml', 'application/xml', 'image/svg+xml', 'template',
    'text/css', 'text/ecmascript', 'text/html', 'text/javascript', 'text/plain',
    'text/template', 'text/xml',
  ],
  quoteCharacter: '"',
  removeAttributeQuotes: true,
  removeComments: true,
  removeScriptTypeAttributes: true,
  removeStyleLinkTypeAttributes: true,
  removeTagWhitespace: false,
  sortAttributes: true,
  sortClassName: true,
  trimCustomFragments: true,
  useShortDoctype: false,
};

// Те же исключения, что были у compress. /demo/ попал туда не случайно: на
// dist/client/demo/hyperui-components/index.html минификатор падал каждую сборку
// («Cannot compress file»), см. лог CI.
const EXCLUDE = [/metodichki\//, /demo\//];

const CACHE_DIR = 'node_modules/.cache/html-minify';

async function* walkHtml(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walkHtml(full);
    else if (entry.name.endsWith('.html')) yield full;
  }
}

export default function htmlMinifyCached() {
  return {
    name: 'html-minify-cached',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        // Первый проход build.sh собирается ради gen-articles.mjs, его dist/
        // выбрасывается — минифицировать его незачем.
        if (process.env.SKIP_COMPRESS === '1') {
          logger.info('SKIP_COMPRESS=1 — минификация HTML пропущена');
          return;
        }

        const root = new URL('./', dir).pathname;
        await fs.mkdir(CACHE_DIR, { recursive: true });

        let hits = 0, misses = 0, failed = 0, saved = 0;
        const started = Date.now();

        for await (const file of walkHtml(root)) {
          if (EXCLUDE.some((re) => re.test(file))) continue;

          const source = await fs.readFile(file, 'utf8');
          const key = createHash('sha1').update(source).digest('hex');
          const cached = path.join(CACHE_DIR, `${key}.html`);

          let output = null;
          try {
            output = await fs.readFile(cached, 'utf8');
            hits++;
          } catch {
            try {
              output = await minify(source, MINIFY_OPTIONS);
              misses++;
              await fs.writeFile(cached, output);
            } catch (e) {
              // Битую страницу оставляем неминифицированной, как делал compress:
              // сборку из-за неё ронять нельзя, но и молчать не будем.
              logger.warn(`не удалось минифицировать ${path.relative(root, file)}: ${e.message}`);
              failed++;
              continue;
            }
          }

          saved += Buffer.byteLength(source) - Buffer.byteLength(output);
          await fs.writeFile(file, output);
        }

        const secs = ((Date.now() - started) / 1000).toFixed(1);
        logger.info(
          `HTML: ${hits} из кэша, ${misses} пересчитано${failed ? `, ${failed} с ошибкой` : ''} ` +
          `— ${(saved / 1024 / 1024).toFixed(2)} MB за ${secs}с`
        );
      },
    },
  };
}
