/**
 * ingest-site-content.mjs — загружает ВСЕ структурированные данные сайта в RAG.
 *
 * Что загружает:
 *   - Отзывы родителей (src/data/reviews.ts)
 *   - FAQ (src/data/faq.ts)
 *   - Возражения + тональность (из systemPrompt)
 *   - Позиционирование бренда (_notes/)
 *   - Статьи блога (src/pages/stati/)
 *   - Факты о лагере (адрес, питание, безопасность и пр.)
 *
 * Запуск:
 *   DATABASE_URL=... OPENAI_API_KEY=... node scripts/ingest-site-content.mjs
 *   node scripts/ingest-site-content.mjs --dry   # только покажет что будет загружено
 */

import https from 'node:https';
import pg from 'pg';
import fs from 'node:fs';
import path from 'node:path';

const DRY = process.argv.includes('--dry');
const OPENAI_API_KEY = process.env.OPENAI_API_KEY;
const DATABASE_URL = process.env.DATABASE_URL || 'postgresql://aidacamp:aidacamp2026@localhost:5432/aidacamp';

if (!OPENAI_API_KEY && !DRY) { console.error('❌  OPENAI_API_KEY не задан'); process.exit(1); }

const pool = new pg.Pool({ connectionString: DATABASE_URL, max: 2 });

const CHUNK_SIZE = 500;
const CHUNK_OVERLAP = 100;
const BATCH = 50;
const DELAY_MS = 600;

// ── Helpers ──────────────────────────────────────────────────────────────────

function chunkText(text, source) {
  const paras = text.split(/\n{2,}/).map(p => p.trim()).filter(p => p.length > 20);
  const chunks = [];
  let buf = '';
  for (const para of paras) {
    if ((buf + '\n' + para).length > CHUNK_SIZE && buf.length > 0) {
      chunks.push({ text: buf.trim(), source });
      buf = buf.slice(-CHUNK_OVERLAP) + '\n' + para;
    } else {
      buf = buf ? buf + '\n' + para : para;
    }
  }
  if (buf.trim().length > 30) chunks.push({ text: buf.trim(), source });
  return chunks;
}

async function embed(texts) {
  if (DRY) return texts.map(() => new Array(1536).fill(0));
  return new Promise((resolve, reject) => {
    const body = JSON.stringify({ input: texts, model: 'text-embedding-3-small' });
    const req = https.request({
      hostname: 'api.openai.com', path: '/v1/embeddings', method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${OPENAI_API_KEY}`, 'Content-Length': Buffer.byteLength(body) },
    }, res => {
      let data = '';
      res.on('data', d => data += d);
      res.on('end', () => {
        try {
          const json = JSON.parse(data);
          if (json.error) return reject(new Error(json.error.message));
          resolve(json.data.sort((a,b)=>a.index-b.index).map(d=>d.embedding));
        } catch(e) { reject(e); }
      });
    });
    req.on('error', reject);
    req.write(body); req.end();
  });
}

async function insertBatch(chunks, vecs) {
  if (DRY) return;
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    for (let i = 0; i < chunks.length; i++) {
      await client.query(
        'INSERT INTO knowledge_chunks (source, text, embedding) VALUES ($1, $2, $3::vector)',
        [chunks[i].source, chunks[i].text, '[' + vecs[i].join(',') + ']']
      );
    }
    await client.query('COMMIT');
  } catch(e) { await client.query('ROLLBACK'); throw e; }
  finally { client.release(); }
}

async function getExistingSources() {
  if (DRY) return new Set();
  const { rows } = await pool.query('SELECT DISTINCT source FROM knowledge_chunks');
  return new Set(rows.map(r => r.source));
}

async function ingestSource(source, text, existingSources) {
  if (existingSources.has(source)) { console.log(`  skip (уже есть): ${source}`); return 0; }
  const chunks = chunkText(text, source);
  if (!chunks.length) { console.log(`  пусто: ${source}`); return 0; }
  console.log(`  ${source}: ${chunks.length} чанков`);
  if (DRY) { chunks.slice(0,2).forEach(c => console.log(`    "${c.text.slice(0,80)}..."`)); return chunks.length; }
  let saved = 0;
  for (let i = 0; i < chunks.length; i += BATCH) {
    const batch = chunks.slice(i, i + BATCH);
    const vecs = await embed(batch.map(c => c.text));
    await insertBatch(batch, vecs);
    saved += batch.length;
    if (i + BATCH < chunks.length) await new Promise(r => setTimeout(r, DELAY_MS));
  }
  return saved;
}

