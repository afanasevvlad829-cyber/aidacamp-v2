// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  console.log('🚀 Загрузка контента сайта в RAG\n');
  if (DRY) console.log('⚠️  DRY режим — БД не трогаем\n');

  const existing = await getExistingSources();
  console.log(`В БД уже: ${existing.size} источников\n`);

  const sources = [
    { id: 'site_reviews_2026',    text: buildReviewsText() },
    { id: 'site_faq_2026',        text: buildFaqText() },
    { id: 'site_facts_2026',      text: buildFactsText() },
    { id: 'site_objections_2026', text: buildObjectionsText() },
    { id: 'site_stories_2026',    text: buildStoriesText() },
  ];

  // Статьи блога
  const statiDir = path.join(process.cwd(), 'src/pages/stati');
  if (fs.existsSync(statiDir)) {
    const files = fs.readdirSync(statiDir).filter(f => f.endsWith('.astro'));
    for (const f of files) {
      const content = fs.readFileSync(path.join(statiDir, f), 'utf-8');
      // Убираем Astro-разметку, оставляем текст
      const text = content
        .replace(/---[\s\S]*?---/g, '')           // frontmatter
        .replace(/<script[\s\S]*?<\/script>/g, '') // scripts
        .replace(/<style[\s\S]*?<\/style>/g, '')   // styles
        .replace(/<[^>]+>/g, ' ')                  // HTML теги
        .replace(/\{[^}]+\}/g, ' ')                // Astro выражения
        .replace(/\s{3,}/g, '\n\n')
        .trim();
      if (text.length > 200) {
        sources.push({ id: `article_${f.replace('.astro','')}`, text });
      }
    }
  }

  let totalNew = 0;
  for (const { id, text } of sources) {
    const n = await ingestSource(id, text, existing);
    totalNew += n;
  }

  if (!DRY) {
    const { rows } = await pool.query('SELECT COUNT(*) as n FROM knowledge_chunks');
    console.log(`\n✅ Готово. Всего в БД: ${rows[0].n} чанков (+${totalNew} новых)`);
    await pool.end();
  } else {
    console.log(`\n✅ DRY: загрузили бы ${totalNew} чанков из ${sources.length} источников`);
    await pool.end();
  }
}

main().catch(e => { console.error('❌', e.message); process.exit(1); });
