#!/usr/bin/env bash
# check-daria-child.sh — Дарья мама ДОЧЕРИ, не сына.
#
# Зачем (09.09.2026). Инвариант из CLAUDE.md: «Дарья — мама дочери (не сына!)».
# Он держался только текстом инструкции, статической проверки не было — и
# 09.09.2026 в dev уехала правка «хотела бы видеть обучение своего сына»
# (MomStory.astro:90). Она была внесена НАМЕРЕННО, как приманка для проверки
# CI-ревью, но откатить её перед мержем забыли: коммит b73e51d4 так и остался
# в dev, и при ближайшем выкате главная заговорила бы от лица Дарьи про сына.
#
# Поймано вручную, до прода. Этот страж делает поимку автоматической.
#
# Правило: в клиентских текстах Дарья не может быть мамой сына. Ловим формы
# «сын» рядом с речью от её лица. Проверка узкая — только прямые конструкции
# принадлежности («своего сына», «моего сына», «для сына»), чтобы не мешать
# статьям, где сын упоминается как пример постороннего ребёнка.

set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"; cd "$(dirname "$SCRIPT_DIR")"

# Компоненты и страницы, где текст идёт от лица Дарьи.
FILES="src/components/MomStory.astro src/pages/founders.astro"

BAD=""
for f in $FILES; do
  [ -f "$f" ] || continue
  HITS=$(grep -nE '(своего|моего|для|у моего|её|его) сына' "$f" || true)
  [ -n "$HITS" ] && BAD="${BAD}${f}:\n${HITS}\n"
done

if [ -n "$BAD" ]; then
  echo "❌ Дарья — мама ДОЧЕРИ, не сына (инвариант CLAUDE.md). Найдено:"
  printf "%b" "$BAD"
  echo "   Исправь на «дочери» или переформулируй нейтрально («ребёнка»)."
  exit 1
fi

echo "✅ Дарья: инвариант «мама дочери» соблюдён."
