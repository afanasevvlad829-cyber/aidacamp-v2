type LiveShift = {
  id: string; name: string; dates: string; days: number; price: number;
  available: boolean; popular?: boolean; short?: boolean;
  enrolled: number; total: number;
};

function buildShiftsText(shifts: LiveShift[]): string {
  return shifts.map(s => {
    const free = s.total - s.enrolled;
    const freeDeclension = free === 1 ? 'место' : free < 5 ? 'места' : 'мест';
    const freeStr = free <= 5 ? ` — осталось ${free} ${freeDeclension}` : '';
    const popularStr = s.popular ? ' — самая популярная' : '';
    const shortStr = s.short ? ' (короткая)' : '';
    const availStr = !s.available ? ' — МЕСТ НЕТ' : '';
    return `- ${s.name}${shortStr}: ${s.dates} (${s.days} дней), ${s.price.toLocaleString('ru')} ₽, записалось ${s.enrolled}/${s.total}${freeStr}${popularStr}${availStr}`;
  }).join('\n');
}

