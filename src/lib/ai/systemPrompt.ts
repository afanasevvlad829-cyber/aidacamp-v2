function getEnrolledByAge(shifts: LiveShift[], age: number): string {
  const key = age <= 9 ? '7-9' : age <= 12 ? '10-12' : '13-16';
  const counts: string[] = [];
  for (const s of shifts) {
    if (!s.available) continue;
    const byAge = (s as any).enrolledByAge;
    const n = byAge?.[key];
    if (n) counts.push(`${s.name}: ${n} детей`);
  }
  return counts.join(', ');
}

