// Хелпер для социального доказательства по возрасту
function getEnrolledByAge(age: number): string {
  let ageKey: string;
  if (age <= 9) ageKey = '7-9';
  else if (age <= 12) ageKey = '10-12';
  else ageKey = '13-16';

  const counts: string[] = [];
  for (const s of campData.shifts) {
    if (s.available && s.enrolledByAge) {
      const n = s.enrolledByAge[ageKey as keyof typeof s.enrolledByAge];
      if (n) counts.push(`${s.name}: ${n} детей`);
    }
  }
  return counts.length ? counts.join(', ') : '';
}

