/** Найти первый шаблон, чьи триггеры срабатывают на user message. */
/** Детектор multi-part вопроса: 2+ '?' или нумерация «1) ... 2) ...» */
function isMultiPartQuestion(message: string): boolean {
  const qMarks = (message.match(/\?/g) || []).length;
  if (qMarks >= 2) return true;
  if (/\b1[\.\)]\s.*\b2[\.\)]\s/s.test(message)) return true;
  return false;
}

export function matchEscalation(message: string): EscalationTemplate | null {
  // Multi-part вопросы (3 в одном) — не отдавать в template-эскалацию,
  // пусть LLM ответит по всем частям. Исключение: если первый match — это medical/legal/divorce,
  // там лучше эскалировать всё равно (риск важнее multi-part).
  const multipart = isMultiPartQuestion(message);
  for (const t of ESCALATION_TEMPLATES) {
    if (t.triggers.length === 0) continue; // fallback не по триггерам
    if (t.triggers.some(re => re.test(message))) {
      if (multipart && !['special_needs'].includes(t.id)) {
        return null; // pass to LLM
      }
      return t;
    }
  }
  return null;
}

/** Готовый JSON-ответ из шаблона (формат как у /api/ask). */
export function templateToResponse(t: EscalationTemplate): string {
  return JSON.stringify({
    state: 'ok',
    text: t.text,
    block_type: t.block_type ?? null,
    block_data: t.block_data ?? null,
    chips: t.chips ?? [],
  });
}
