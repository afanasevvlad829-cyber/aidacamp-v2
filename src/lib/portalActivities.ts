export interface ActivityFile {
  name: string;       // отображаемое имя
  href: string;       // относительный URL
  icon?: string;      // bi-* иконка
  desc?: string;      // краткое описание
}

export interface ActivityStage {
  title: string;
  text: string;
}

export interface Activity {
  slug: string;
  title: string;
  desc: string;
  author?: string;             // по умолчанию «Александр Ташкин»
  duration?: string;           // напр. «90 минут × 2/день»
  ages?: string;               // напр. «10–14»
  /** Цель занятия — что мы хотим, чтобы ребёнок понял или научился. */
  goal?: string;
  /** Что делаем — пошаговое описание процесса. */
  doing?: string[];
  /** Какой результат получаем — итог занятия. */
  result?: string;
  /** Приборы и материалы — что физически нужно на занятии. */
  materials?: string[];
  /** Что требуется от ребёнка / преподавателя заранее. */
  requirements?: string[];
  /** Этапы по времени (если применимо). */
  stages?: ActivityStage[];
  /** Файлы (PDF/PPTX/ZIP/HTML). */
  files?: ActivityFile[];
  /** Внешние ссылки (порталы, академии). */
  links?: ActivityFile[];
  hasImagesZip?: boolean;      // есть ли архив картинок (старый формат)
  hasPreview?: boolean;        // есть ли preview.png/preview-thumb.webp
}

