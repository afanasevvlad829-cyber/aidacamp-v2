/**
 * Площадка смены по датам: всё, что не июнь–август, проходит в «Воробьях».
 * Летние смены возвращают null — у них площадка своя и ссылка не нужна.
 */
export function getShiftLocation(shift: Pick<Shift, 'startDate'>): typeof VOROBI | null {
  const m = Number(shift.startDate?.slice(5, 7));
  if (!m || (m >= 6 && m <= 8)) return null;
  return VOROBI;
}
