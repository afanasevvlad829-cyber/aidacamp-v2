export interface SeasonDay {
  day: string;      // «День 1 · заезд»
  title: string;    // короткий заголовок дня
  text: string;     // что происходит
}

export interface SeasonOption {
  icon: string;     // bootstrap-иконка из icons-manifest.json
  title: string;
  text: string;
  href?: string;    // ссылка «подробнее» (размещение, статья про экономику и т.п.)
  hrefLabel?: string;
}

export interface SeasonFaqItem { q: string; a: string; }

export interface SeasonConfig {
  slug: string;                 // slug предзаписи: osen-2026
  path: string;                 // путь страницы: /lager-na-osennie-kanikuly
  title: string;                // <title>
  description: string;          // meta description
  h1: string;
  subtitle: string;             // подзаголовок hero
  breadcrumb: string;
  heroImage: string;
  heroImageAlt: string;
  heroKeywords: string[];       // буллеты в hero
  seasonAcc: string;            // «осеннюю смену 2026» — для формы предзаписи
  seasonMeta: { dates: string; price: string };  // чипы в hero вместо летней меты
  datesBlock: {
    heading: string;
    intro: string;              // абзац с ориентиром дат и дисклеймером
    facts: string[];            // список фактов (цена, вычет, оплата...)
  };
  windows?: string[];           // окна заездов для предзаписи (четверти/триместры)
  windowsBlock?: { heading: string; intro: string; items: string[] };
  schedule: { heading: string; intro: string; days: SeasonDay[] };
  options: { heading: string; intro: string; items: SeasonOption[] };
  faq: { heading: string; items: SeasonFaqItem[] };
}

